import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { planCandidates, type PlanContext } from "./plan.ts";
import type { Config } from "./types.ts";

export const GENERATED_MARK = "<!-- generated by hroute sync-agents; edits are overwritten -->";

const DEFAULT_DESCRIPTIONS: Record<string, string> = {
  plan: "Use for architecture decisions, hard debugging, security-sensitive design and reviews.",
  impl: "Use for normal feature implementation and bug fixes.",
  quick: "Use PROACTIVELY for grep, finding where something is defined, renames, summaries and small mechanical edits.",
};

/**
 * Render a Claude Code subagent for a tier. The model is the first Claude
 * target that is usable right now, so re-running sync tracks 5h usage.
 * With no usable Claude target the model line is omitted (inherits the session's).
 */
export function renderAgent(config: Config, tier: string, ctx: PlanContext, prefix = "hr-"): string {
  const t = config.tiers[tier]!;
  const pick = planCandidates(config, tier, ctx).find((c) => !c.skip && c.target.kind === "claude" && c.target.model);
  const description = (t.description ?? DEFAULT_DESCRIPTIONS[tier] ?? `Tier "${tier}" tasks.`).replace(/\n/g, " ");
  return [
    "---",
    `name: ${prefix}${tier}`,
    `description: ${description}`,
    ...(pick ? [`model: ${pick.target.model}`] : []),
    "---",
    GENERATED_MARK,
    t.instructions ?? "Complete the task and return the result concisely, without restating the question.",
    "",
  ].join("\n");
}

export interface SyncedAgent {
  file: string;
  model: string | null;
  action: "written" | "unchanged" | "skipped-user-file";
}

export function syncAgents(config: Config, ctx: PlanContext, dir: string, prefix = "hr-"): SyncedAgent[] {
  mkdirSync(dir, { recursive: true });
  return Object.keys(config.tiers).map((tier) => {
    const file = join(dir, `${prefix}${tier}.md`);
    const body = renderAgent(config, tier, ctx, prefix);
    const model = /^model: (.+)$/m.exec(body)?.[1] ?? null;
    if (existsSync(file)) {
      const current = readFileSync(file, "utf8");
      if (!current.includes(GENERATED_MARK)) return { file, model, action: "skipped-user-file" as const };
      if (current === body) return { file, model, action: "unchanged" as const };
    }
    writeFileSync(file, body);
    return { file, model, action: "written" as const };
  });
}
